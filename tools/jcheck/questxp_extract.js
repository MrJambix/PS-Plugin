#!/usr/bin/env node
// What each quest pays in experience, for the XP bars (Jambix AIO 1.7.6).
//
//   node tools/jcheck/questxp_extract.js [--addons <AddOns dir>] [--out <file>]
//
// The user, 2026-10-10: "on ESP for forever Write up a moveable EXP Bar that
// show's Exp/hour counts how much EXP going to get and fills the bar once
// completed quests are Turned in and one that does the same but for all
// quests in my Questlog". No client call says what a quest in your log pays
// (core.quests has no reward-XP reader, and Forever's gamelua bridge is down),
// so the bars read this table.
//
// THE TABLE is QuestieDB's own: support/Forever/QuestXP/xpDB-classic.lua in the
// Forever client, the one QuestieDB_Forever.toc loads and Questie's
// QuestXP:GetQuestLogRewardXP reads. Each row is [quest id] = { quest level,
// base xp }: what the quest pays at or under its level + 5, before Questie's
// level penalty. 3,494 rows at QuestieDB 1.0.5, byte-identical to the Era
// table. Checked against Forever: the API recorder's QUEST_TURNED_IN examples
// (244 -> 290, 65 -> 1350) are exactly the table's numbers.
//
// FOREVER'S OWN QUESTS (ids past 90000) are not in it. For those the bars
// estimate from the quest's level: `typical`, what a standard quest of that
// level pays in the table (see `standard` below), until a turn-in teaches the
// real number (modules/xpbar.lua keeps what it learns).
//
// WRITTEN: scripts/jambix_aio/modules/questxp_data.lua. Do not edit it by
// hand: run this again.
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..", "..");
const argv = process.argv.slice(2);
const opt = name => { const i = argv.indexOf(name); return i >= 0 ? argv[i + 1] : null; };
const ADDONS = opt("--addons") || "C:/Program Files (x86)/World of Warcraft/_classic_beta_/Interface/AddOns";
const OUT = opt("--out") || path.join(ROOT, "scripts", "jambix_aio", "modules", "questxp_data.lua");
const SOURCE = path.join(ADDONS, "QuestieDB", "support", "Forever", "QuestXP", "xpDB-classic.lua");
const MAX_LEVEL = 60;

function version() {
    try {
        const toc = fs.readFileSync(path.join(ADDONS, "QuestieDB", "QuestieDB_Forever.toc"), "utf8");
        const m = toc.match(/^##\s*Version:\s*(.+)$/m);
        return m ? m[1].trim() : "?";
    } catch (e) { return "?"; }
}

const text = fs.readFileSync(SOURCE, "utf8");
const rows = [];
let skipped = 0;
const re = /\[(\d+)\]\s*=\s*\{\s*(-?\d+)\s*,\s*(-?\d+)\s*\}/g;
let m;
while ((m = re.exec(text))) {
    const id = +m[1], level = +m[2], xp = +m[3];
    // Questie: "-1 as a level for quests that are event quests", and it pays
    // 0 for those; so do the bars.
    if (level <= 0 || xp <= 0) { skipped++; continue; }
    rows.push([id, level, xp]);
}
if (rows.length < 1000) throw new Error(`only ${rows.length} rows read from ${SOURCE}`);
rows.sort((a, b) => a[0] - b[0]);

// What a standard quest pays at each level, 1..MAX_LEVEL: the most common
// base xp among the level's upper half (the median and up; a tie takes the
// lower: 4050 over 5050 at 46). The plain median was a delivery quest's half
// or quarter wherever a level has many of them (420 at 10, 780 at 20, 2800
// at 55); the upper
// half's most common value is the full quest's: 840, 1550, 2450 at 30, 4700
// at 50, 6600 at 60. Then never less than the level below's, and a level
// with no quest takes the nearest one that has some.
const by = {};
for (const [, level, xp] of rows) (by[level] = by[level] || []).push(xp);
function standard(a) {
    const s = a.slice().sort((x, y) => x - y);
    const med = s[Math.floor((s.length - 1) / 2)];
    const count = new Map();
    for (const x of s) if (x >= med) count.set(x, (count.get(x) || 0) + 1);
    let best = med, n = 0;
    for (const [x, c] of count) if (c > n || (c === n && x < best)) { best = x; n = c; }
    return best;
}
const typical = [];
for (let lv = 1; lv <= MAX_LEVEL; lv++) {
    let v = null;
    for (let d = 0; d <= MAX_LEVEL && v === null; d++) {
        if (by[lv - d]) v = standard(by[lv - d]);
        else if (by[lv + d]) v = standard(by[lv + d]);
    }
    typical.push(Math.max(v, typical.length ? typical[typical.length - 1] : 0));
}

const out = [];
out.push("-- Jambix AIO / questxp_data -- GENERATED by tools/jcheck/questxp_extract.js from the");
out.push("-- QuestieDB in the Forever client (support/Forever/QuestXP/xpDB-classic.lua, the table");
out.push("-- Questie's QuestXP reads). Do not edit by hand: run that script again.");
out.push("--");
out.push("-- xp[quest id] = { quest level, base xp }: what the quest pays at or under its level + 5,");
out.push("--                 before the level penalty modules/xpbar.lua applies.");
out.push("-- typical[level] = what a standard quest of that level pays here (the most common amount");
out.push("--                 in its upper half): the estimate for a quest the table lacks (Forever's own).");
out.push("return {");
out.push(`    questdb = ${JSON.stringify("QuestieDB " + version() + " (Forever)")},`);
out.push(`    count = ${rows.length},`);
out.push(`    typical = { ${typical.join(", ")} },`);
out.push("    xp = {");
for (let i = 0; i < rows.length; i += 6) {
    const chunk = rows.slice(i, i + 6).map(([id, level, xp]) => `[${id}] = { ${level}, ${xp} }`);
    out.push("        " + chunk.join(", ") + ",");
}
out.push("    },");
out.push("}");
fs.writeFileSync(OUT, out.join("\n") + "\n");
console.log(`${rows.length} quests (${skipped} event quests skipped), typical by level ${typical.join(" ")}`);
console.log(`written ${path.relative(ROOT, OUT)} (${(fs.statSync(OUT).size / 1024).toFixed(0)} KB)`);
